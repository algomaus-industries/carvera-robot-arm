ARM_BASE_H = 0.103 + cl.SEAT_Z - 0.047
PEDESTAL_LO = (-0.020, -0.035, 0.0)
PEDESTAL_HI = (0.050, 0.075, ARM_BASE_H)
CART = dict(w=0.355, d=0.435, h=0.84 + 0.150 - cl.SEAT_Z)
# ---- mirrored from configs/carvera_so101/gen_cell_configs.py (world, metres)
CART_C = (-0.0175, -0.1525)
