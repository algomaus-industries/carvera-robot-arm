# Close-up views of the jaws: eye x,y,z, centre x,y,z (tool frame, mm).
CAMERAS = {
  "view_closed": "-18,-30,48,-3,0,0",
  "view_fixed": "-45,-12,22,1,0,-4",
  "view_moving": "42,-44,22,-10,3,-3",
}


def export():
  cmd = shlex.split(os.environ.get("OPENSCAD", "openscad"))
  for d, scad, part, outs in PARTS:
    os.makedirs(os.path.join(FAB, d, "out"), exist_ok=True)
    for ext in outs:
      out = os.path.join(FAB, d, "out", f"{part}.{ext}")
      args = cmd + ["--backend=manifold", "-D", f'part="{part}"', "-o", out]
      if part.startswith("sim_"):
        # Sim meshes: circles by angle and length, not 64 segments each (a
        # 6.6 mm seat hole needs ~10), so RViz gets ~10x fewer triangles.
        args += ["-D", "$fn=0", "-D", "$fa=8", "-D", "$fs=2.5"]
      if d == "jaws" and ext == "stl":
        args += ["--export-format", "binstl"]  # ~25k facets each: 1 MB, not 8
      if ext == "png" and part in CAMERAS:
        args += [
          "--render",
          "--imgsize=900,900",
          "--colorscheme=Tomorrow",
          "--camera=" + CAMERAS[part],
        ]
      elif ext == "png":
        args += [
          "--render",
          "--imgsize=1200,900",
          "--viewall",
          "--autocenter",
          "--colorscheme=Tomorrow",
          "--camera=0,0,0,55,0,30,0",
        ]
      r = subprocess.run(
        args + [os.path.join(FAB, d, scad)], capture_output=True, text=True
      )
      ok = r.returncode == 0 and os.path.exists(out)
      print(("ok  " if ok else "FAIL") + f" {d}/out/{part}.{ext}")
      if not ok:
        print(r.stderr[-1500:])


if __name__ == "__main__":
  params()
  if "--params" not in sys.argv:
    export()
