"""Writes the fabrication parameter files and exports every part.

The numbers come from the same places the sim models use, so the real cell
matches the simulated one:
  models/bit_carousel/carousel_layout.py   carousel seats and mechanics
  models/so101/build_so101.py              pedestal and cart (mirrored below,
                                           that script needs Blender)
  configs/carvera_so101/gen_cell_configs.py where things stand on the cart

  python3 fab/gen_fab.py            # params + STL / DXF / SVG / PNG into fab/*/out/
  python3 fab/gen_fab.py --params   # params only

Exports need OpenSCAD with the Manifold backend; set OPENSCAD to override
the command (default: openscad).
"""

